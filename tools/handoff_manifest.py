"""Maintain `handoff/provenance.tsv` and `handoff/README.md`.

`handoff/` carries over a hundred tables from three different origins: generated by
a tool, derived from another table, or typed by hand. Nothing in the tree said
which, and that ambiguity already cost us once — `psin-vocabulary.tsv` was assumed
to be generated output and a regeneration attempt made it worse.

The fix is an explicit manifest rather than a heuristic:

* `handoff/provenance.tsv` lists every table with its status and producer. It is
  committed, and correcting an entry is a one-line edit.
* `--check` fails if a table exists that the manifest does not list, or if the
  manifest lists a file that is gone. It also reports how many entries still have
  `status=unknown`, which is a to-do counter rather than a failure.
* `handoff/README.md` is rendered from the manifest for humans.

    python3 tools/handoff_manifest.py            # refresh manifest + README
    python3 tools/handoff_manifest.py --check    # verify nothing is unlisted
"""

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HANDOFF = ROOT / "handoff"
PROVENANCE = HANDOFF / "provenance.tsv"
README = HANDOFF / "README.md"

# Assembled by hand or from external meta: not reproducible from the archives.
CURATED = {
    "names.tsv": "JOAAT names from CodeWalker meta plus harvested corpus",
    "psin-vocabulary.tsv": "named PSIN values grouped by hand",
    "bone-hash-names-curated.tsv": "bones confirmed by hand against geometry",
    "packs-label-queue.tsv": "work queue, not a derived result",
}

# Produced before the tools convention existed: no current tool writes them, and
# they are kept because the docs cite their numbers. Regenerating one means first
# writing the tool that made it.
LEGACY = {
    "data-skeleton-family-links.tsv": "early skeleton-family experiment",
    "remaining-archive-index-sha256.tsv": "verification snapshot of the last archives",
    "remaining-archive-index-verification.tsv": "verification snapshot of the last archives",
    "script-bone-roots-named.tsv": "bone-root naming pass",
    "script-skeleton-0x48dcbb01.tsv": "one skeleton, inspected by hand",
}

# Table families emitted in bulk by one driver, matched on prefix or suffix.
FAMILY_PREFIXES = {
    "corpus-pass/entries-": "tools/corpus_pass.sh — per-archive entry manifests",
    "corpus-pass/pack-model-": "tools/corpus_pass.sh — per-archive model fits",
}
FAMILY_SUFFIXES = {
    "-entries-chains.tsv": "family: entry reconciliation",
    "-descriptors.tsv": "family: bvh4 descriptor manifests",
    "-summary.tsv": "family: report summaries",
    "-inventory.tsv": "family: inventory reports",
}


def tool_text():
    parts = []
    for path in sorted((ROOT / "tools").iterdir()):
        if path.suffix in {".py", ".sh"} and path.is_file():
            parts.append(path.read_text(errors="ignore"))
    return "\n".join(parts)


def guess_producer(name, text, tools):
    stem = name[:-4] if name.endswith(".tsv") else name
    if name in text:
        return "exact name in a tool"
    if stem in text:
        return f"stem in a tool: {stem}"
    for prefix, owner in FAMILY_PREFIXES.items():
        if name.startswith(prefix):
            return owner
    for suffix, owner in FAMILY_SUFFIXES.items():
        if name.endswith(suffix):
            return owner
    # last resort: the table stem usually contains its producer's file name
    flat = stem.replace("-", "_").split("/")[-1]
    best = ""
    for tool in tools:
        candidate = tool.stem
        if candidate and candidate in flat and len(candidate) > len(best):
            best = candidate
    if best:
        return f"tool name appears in the table name: tools/{best}.py"
    return ""


def table_files():
    files = sorted(HANDOFF.glob("*.tsv")) + sorted((HANDOFF / "corpus-pass").glob("*.tsv"))
    return [path for path in files if path.name != "provenance.tsv"]


def describe(path):
    with path.open() as handle:
        reader = csv.reader(handle, delimiter="\t")
        try:
            header = next(reader)
        except StopIteration:
            return 0, 0
        rows = sum(1 for _ in reader)
    return rows, len(header)


def relative(path):
    return str(path.relative_to(HANDOFF))


def load_manifest():
    if not PROVENANCE.is_file():
        return {}
    with PROVENANCE.open() as handle:
        return {row["file"]: row for row in csv.DictReader(handle, delimiter="\t")}


def refresh():
    text = tool_text()
    tools = sorted(path for path in (ROOT / "tools").iterdir()
                   if path.suffix in {".py", ".sh"} and path.is_file())
    known = load_manifest()
    rows = []
    for path in table_files():
        name = relative(path)
        count, columns = describe(path)
        previous = known.get(name)
        if previous and previous.get("status") in {"generated", "curated", "legacy"}:
            # keep a settled entry; only re-guess the ones still unknown
            status = previous["status"]
            producer = previous.get("producer", "")
        elif path.name in CURATED:
            status, producer = "curated", CURATED[path.name]
        elif path.name in LEGACY:
            status, producer = "legacy", LEGACY[path.name]
        else:
            guess = guess_producer(name, text, tools)
            status, producer = ("generated", guess) if guess else ("unknown", "")
        rows.append({"file": name, "rows": count, "columns": columns,
                     "status": status, "producer": producer})
    PROVENANCE.parent.mkdir(parents=True, exist_ok=True)
    with PROVENANCE.open("w") as handle:
        writer = csv.DictWriter(handle, fieldnames=["file", "rows", "columns",
                                                    "status", "producer"],
                                delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return rows


def render(rows):
    generated = [r for r in rows if r["status"] == "generated"]
    curated = [r for r in rows if r["status"] == "curated"]
    unknown = [r for r in rows if r["status"] == "unknown"]
    out = ["# Handoff tables", "",
           "Every table here, its size, and where it comes from. Rendered from",
           "`handoff/provenance.tsv` by `tools/handoff_manifest.py`; that manifest is the",
           "source of truth and is checked by `tools/check.sh`.", "",
           f"**{len(rows)} tables** — {len(generated)} generated, {len(curated)} curated, "
           f"{len([r for r in rows if r['status'] == 'legacy'])} legacy, "
           f"{len(unknown)} unclassified.", ""]
    if unknown:
        out += ["## Unclassified — producer not identified yet", "",
                "These are listed so the question stays visible; each needs either a",
                "producer or a curated reason in `provenance.tsv`.", "",
                "| file | rows |", "| --- | ---: |"]
        out += [f"| `{r['file']}` | {r['rows']:,} |" for r in unknown]
        out.append("")
    out += ["## Curated (hand-maintained)", "", "| file | rows | why |",
            "| --- | ---: | --- |"]
    out += [f"| `{r['file']}` | {r['rows']:,} | {r['producer']} |" for r in curated]
    out += ["", "## Generated", "", "| file | rows | cols | producer |",
            "| --- | ---: | ---: | --- |"]
    out += [f"| `{r['file']}` | {r['rows']:,} | {r['columns']} | {r['producer']} |"
            for r in generated]
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="fail if a table is unlisted or a listed table is gone")
    args = parser.parse_args()

    rows = refresh()
    README.write_text(render(rows))
    unknown = sum(1 for row in rows if row["status"] == "unknown")

    if args.check:
        listed = {row["file"] for row in rows}
        present = {relative(path) for path in table_files()}
        missing = sorted(present - listed)
        stale = sorted(listed - present)
        if missing or stale:
            for name in missing:
                print(f"unlisted table: {name}")
            for name in stale:
                print(f"listed but missing: {name}")
            return 1
        print(f"{len(rows)} tables listed, {unknown} still unclassified")
        return 0
    print(f"wrote {PROVENANCE.relative_to(ROOT)} and {README.relative_to(ROOT)} "
          f"({len(rows)} tables, {unknown} unclassified)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
